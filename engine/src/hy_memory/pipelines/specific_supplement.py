"""Question-blind exact-L2 supplement for the Ultra persona catalog.

The supplement is generated after the balanced catalog.  It selects only from
active/latest L2 facts not already represented by that catalog, applies direct
and semantic forget closure, and persists a special internal L6 node.  The node
never enters ordinary Schema recall and consumes no profile slot; Ultra appends
it to the unique visible L0 chain after the balanced catalog.

Raw and ordinary S1 records are never read or mutated by this module.
"""

