async def run_specific_supplement_generation(
    *, user_id: str, vector_store: VectorStoreBase,
    graph_store: Optional[GraphStoreBase], config: MemoryConfig,
) -> Dict[str, Any]:
    """Generate the one user-level supplement, serialized by user_id."""
    from .user_profile_scope import user_profile_lock

    async with user_profile_lock(user_id):
        return await _run_specific_supplement_generation_unlocked(
            user_id=user_id,
            vector_store=vector_store,
            graph_store=graph_store,
            config=config,
        )


async def get_active_specific_supplement(
    graph_store: Optional[GraphStoreBase], *, user_id: str,
) -> Optional[MemoryNode]:
    if not specific_supplement_l0_enabled() or graph_store is None or not user_id:
        return None
    nodes = await _active_supplements(
        graph_store, user_id=user_id,
    )
    nodes = [
        node for node in nodes
        if int((node.custom or {}).get("selected_count") or 0) > 0
        and bool(parse_rendered_specific_entries(node.content))
    ]
    if not nodes:
        return None
    nodes.sort(
        key=lambda node: (
            not bool(str(getattr(node, "agent_id", "") or "").strip()),
            getattr(node, "gmt_created", None) or datetime.min, node.node_id,
        ),
        reverse=True,
    )
    return nodes[0]


def attach_specific_supplement_to_l0(
    l0_results: List[Dict[str, Any]], supplement: Optional[MemoryNode],
) -> tuple[List[Dict[str, Any]], Dict[str, Any]]:
    results = [dict(item) for item in l0_results]
    if supplement is None:
        return results, {
            "enabled": specific_supplement_l0_enabled(), "attached": False,
        }
    if len(results) != 1:
        return results, {
            "enabled": True, "attached": False,
            "reason": f"l0_count={len(results)}",
            "supplement_node_id": supplement.node_id,
        }
    item = dict(results[0])
    item["_specific_supplement_suffix"] = str(supplement.content or "").strip()
    item["_specific_supplement_node_id"] = supplement.node_id
    item["_specific_supplement_count"] = int(
        (supplement.custom or {}).get("selected_count") or 0
    )
    results[0] = item
    return results, {
        "enabled": True, "attached": True,
        "supplement_node_id": supplement.node_id,
        "selected_count": item["_specific_supplement_count"],
        "supplement_chars": len(str(supplement.content or "")),
    }
