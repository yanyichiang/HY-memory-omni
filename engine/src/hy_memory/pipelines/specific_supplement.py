SUPPLEMENT_VERSION = 1
SUPPLEMENT_MAX_PER_DOMAIN = 2
SUPPLEMENT_MAX_TOTAL = 16
SUPPLEMENT_MARKER = "System2 specific supplement (exact stored evidence):"
SUPPLEMENT_MATERIALIZATION_VERSION = "exact-evidence-artifact-v1"
_SUPPLEMENT_ITEM_RE = re.compile(r"^- \[([^\]]+)\] (.*)$")

_FORGET_RE = re.compile(
    r"(?i)\b(?:forget|forgotten|do not remember|asked (?:the )?assistant to forget|"
    r"requested (?:that )?.* be forgotten)\b"
)
_ASSISTANT_ADVICE_RE = re.compile(
    r"(?i)^\s*(?:the )?assistant (?:advised|recommended|suggested|explained|outlined)\b"
)
_GENERIC_QUESTION_RE = re.compile(
    r"(?i)^\s*the user (?:asked|wants to know|is curious|wondered)\b"
)
_CURIOUS_RE = re.compile(r"(?i)^\s*the user is curious\b")
_ABBREVIATIONS = ("Dr.", "Mr.", "Mrs.", "Ms.", "Prof.", "St.", "U.S.", "e.g.", "i.e.")

